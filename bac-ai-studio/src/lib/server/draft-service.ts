import fs from 'fs/promises';
import path from 'path';
import { EducationalDraft } from '../types';
import { 
  CONTENT_ROOT, 
  generateUniqueDraftId, 
  resolveSafePath 
} from './path-security';
import { 
  atomicWriteFile, 
  createBackupCopy, 
  fileExists, 
  readJsonFile 
} from './atomic-write';
import { validateDraftPayload, validatePayloadSize } from './validation';

/**
 * Saves or updates an educational draft.
 * Automatically creates a historical backup before overwriting.
 */
export async function saveDraft(draft: EducationalDraft): Promise<EducationalDraft> {
  validateDraftPayload(draft);

  const targetPath = resolveSafePath('drafts/active', draft.draftId, '.json');
  const alreadyExists = await fileExists(targetPath);

  if (alreadyExists) {
    // Read current version to determine backup tag
    const current = await readJsonFile<EducationalDraft>(targetPath);
    const backupId = `${draft.draftId}.v${current.version || 1}.${Date.now()}.bak`;
    const backupPath = resolveSafePath('drafts/backups', backupId, '.json');
    await createBackupCopy(targetPath, backupPath);

    // Bump version and timestamp
    draft.version = (current.version || 1) + 1;
  } else {
    draft.version = draft.version || 1;
  }

  draft.updatedAt = new Date().toISOString();
  draft.schemaVersion = '1.0.0';

  const jsonContent = JSON.stringify(draft, null, 2);
  validatePayloadSize(jsonContent);

  await atomicWriteFile(targetPath, jsonContent);
  return draft;
}

/**
 * Imports a JSON draft generated by Antigravity or an external authoring tool.
 * Validates payload strictly and prevents accidental clobbering.
 */
export async function importDraft(rawJson: unknown): Promise<EducationalDraft> {
  const draft = validateDraftPayload(rawJson);

  // If no draftId was assigned by Antigravity, generate one
  if (!draft.draftId) {
    draft.draftId = generateUniqueDraftId();
  }

  return await saveDraft(draft);
}

/**
 * Reads a single draft by ID.
 */
export async function getDraftById(draftId: string): Promise<EducationalDraft | null> {
  const targetPath = resolveSafePath('drafts/active', draftId, '.json');
  if (await fileExists(targetPath)) {
    return await readJsonFile<EducationalDraft>(targetPath);
  }
  return null;
}

/**
 * Lists all active drafts.
 */
export async function listActiveDrafts(): Promise<EducationalDraft[]> {
  const dir = path.resolve(CONTENT_ROOT, 'drafts/active');
  await fs.mkdir(dir, { recursive: true });

  const files = await fs.readdir(dir);
  const drafts: EducationalDraft[] = [];

  for (const f of files) {
    if (f.endsWith('.json') && !f.includes('.tmp.')) {
      try {
        const fullPath = path.resolve(dir, f);
        const draft = await readJsonFile<EducationalDraft>(fullPath);
        drafts.push(draft);
      } catch {
        // Skip invalid or temporary files
      }
    }
  }

  return drafts.sort((a, b) => new Date(b.updatedAt || b.createdAt).getTime() - new Date(a.updatedAt || a.createdAt).getTime());
}
